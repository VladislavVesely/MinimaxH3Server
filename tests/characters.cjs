const assert=require('node:assert/strict');
const {bindings,header,complete,insert,prepareDraft,needsReview,prefill}=require('../src/h3server/web/characters.js');
const a={id:'a',name:'Ada',description:'Dark hair',voice_description:'Soft delivery',variants:[{id:'v',name:'Blue',description:'Blue coat',image_asset_id:'i'}],voice_asset_id:'s'};
const selected=[{character:a,variant_ids:['v']}];
const draft={reference_images:[{id:'manual',kind:'image'},{id:'i',kind:'image'}],reference_audios:[{id:'s',kind:'audio'}],reference_videos:[]};
const b=bindings(selected,draft);
assert.equal(b[0].label,'<Subject 1>');assert.equal(b[0].picture,'<Picture 2>');assert.equal(b[0].audio,'<Audio 1>');
const h=header(b);assert.ok(h.includes('subject_definitions:'));assert.ok(h.includes('retention_analysis:'));assert.ok(h.includes('<Subject 1> is Ada'));assert.ok(h.includes('voice-timbre'));assert.ok(!h.includes('(S1)'));assert.ok(!h.includes('<Picture 2> is'));
assert.equal(complete('hello <sub',10,b)[0].label,'<Subject 1>');
assert.deepEqual(insert('hello <sub',10,'<Subject 1>'),{text:'hello <Subject 1>',caret:17});
assert.equal(needsReview('Scene with <Subject 1>',b,[]),true);
assert.equal(needsReview('Scene without tags',b,[]),false);
const other={...a,id:'b',name:'Bea'};
const shared=bindings([...selected,{character:other,variant_ids:['v']}],draft);
assert.equal(shared[1].picture,'<Picture 2>');assert.equal(shared[1].audio,'<Audio 1>');
assert.ok(header(shared).includes('<Subject 1> (Soft delivery) and <Subject 2> (Soft delivery)'));
assert.equal(needsReview('Scene <Subject 1>',b,bindings([{character:other,variant_ids:['v']}],draft)),true,'Changing characters must flag authored labels even when the media is shared');
const next=prepareDraft(draft,new Set(['i','s']),[],[]);
assert.deepEqual(next.reference_images.map(a=>a.id),['manual']);assert.equal(draft.reference_images.length,2);
assert.throws(()=>prepareDraft({...draft,reference_images:Array.from({length:9},(_,i)=>({id:String(i)}))},new Set(),[{id:'x',kind:'image'}],[]),/9/);
const scene='[Shot 1] <Subject 1> says <d>[Czech] Ahoj!</d>\n\noverall_soundscape:\nRain.\n\nnon_diegetic_music:\nN/A';
assert.equal(prefill(h+scene,h,b),h+scene);
assert.equal(prefill('subject_definitions:\nEdited\n\ndetailed_description:\n'+scene,'',b),h+scene);
assert.ok(prefill('', '', b).includes('overall_soundscape:'));
assert.throws(()=>prefill(scene,'',b,10),/limit/);
console.log('Character mappings, prompt scaffolding, completion and draft ownership verified');
